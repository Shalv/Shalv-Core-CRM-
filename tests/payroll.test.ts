import assert from 'node:assert/strict';
import { buildDefaultSalaryMasterRecord, calculateEmployeePolicyPayroll, loadAdminPolicyMaster, saveEmployeeAttendance, loadEmployeeAttendance, saveEmployeeSalaryMasters } from '../src/components/payroll/payrollTypes';
const cache = new Map<string,string>();
(globalThis as any).localStorage = { getItem:(k:string)=>cache.get(k) ?? null, setItem:(k:string,v:string)=>cache.set(k,v), removeItem:(k:string)=>cache.delete(k) };
(globalThis as any).fetch = async () => ({ok:true,json:async()=>({success:true})});
const master = {...buildDefaultSalaryMasterRecord({id:'u1',name:'Test',email:'test@example.com'}), monthlyGross:30000, basicPct:50,hraPct:25,specialPct:18,pfAmount:1800,profTax:200,tdsPct:0};
const policy = {...loadAdminPolicyMaster(),monthlyLeaveLimit:1};
const run = (patch:any={}) => calculateEmployeePolicyPayroll({monthKey:'2026-09',master,policy,loansOverride:[],...patch});
assert.equal(run().grossEarnings,30000);
assert.equal(run().netPayable,28000);
assert.equal(run({master:{...master,monthlyGross:0}}).grossEarnings,0);
assert.equal(run({master:{...master,monthlyGross:0}}).netPayable,0);
assert.equal(run({grossOverride:0}).baseMonthlyGross,0);
assert.equal(run({master:{...master,lopDays:3}}).grossEarnings,27000);
assert.equal(run({master:{...master,lopDays:100}}).grossEarnings,0);
assert.equal(run({master:{...master,basicPct:90,hraPct:90,specialPct:90}}).grossEarnings,30000);
const leave = {id:'lv',startDate:'2026-08-01',endDate:'2026-08-02',days:2,status:'Unauthorized Absence (LOP)',leaveType:'Privilege Leave'};
assert.equal(run({leaves:[leave]}).lopDays,0);
assert.equal(run({leaves:[{...leave,startDate:'2026-09-01',endDate:'2026-09-02'}]}).lopDays,2);
assert.equal(run({leaves:[{...leave,startDate:'2026-08-31',endDate:'2026-09-01'}]}).lopDays,1);
const claim={id:'c',amount:500,status:'Approved & Queued for Payroll',expenseDate:'2026-08-10'};
assert.equal(run({claims:[claim]}).approvedReimbursements,0);
assert.equal(run({claims:[{...claim,expenseDate:'2026-09-10'}]}).approvedReimbursements,500);
assert.equal(run({attendance:{date:'2026-08-10',punchInTime:'01:30 PM',punchOutTime:'02:00 PM',lateCountThisMonth:8}}).lopDays,0);
const day={date:'2026-09-10',punchInTime:'09:30 AM',punchOutTime:'02:00 PM',breakDurationMins:0,lateCountThisMonth:0};
assert.equal(run({attendance:{...day,dailyRecords:{'2026-09-09':{...day,date:'2026-09-09'}}}}).lopDays,1);
const blank=buildDefaultSalaryMasterRecord({id:'u2'});
assert.equal(blank.monthlyGross,0);assert.equal(blank.bankAccountNo,'');assert.equal(blank.panNumber,'');
saveEmployeeSalaryMasters({u1:master});
assert.notEqual(buildDefaultSalaryMasterRecord({id:'u2'}).empCode,master.empCode);
saveEmployeeAttendance('u1',day as any);
saveEmployeeAttendance('u1',{...day,date:'2026-09-11'} as any);
assert.equal(Object.keys(loadEmployeeAttendance('u1').dailyRecords || {}).length,2);
assert.equal(loadEmployeeAttendance('u2').punchInTime,null);
const unlinkedMaster = { ...master, accessType: 'payroll_only' as const, syncedWithCrm: false };
saveEmployeeSalaryMasters({ u1: unlinkedMaster });
assert.equal(unlinkedMaster.accessType, 'payroll_only');
assert.equal(unlinkedMaster.syncedWithCrm, false);
console.log('Payroll regression checks passed: salary, zero pay, LOP, date scope, component totals, identity, attendance history, and CRM unlinking.');
